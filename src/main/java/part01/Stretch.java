public class Stretch {
    public static void main(String[] args) {
        // Prints A and B.
        System.out.print("A");
        System.out.println("B");

        // Prints C.
        System.out.print("C\n");

        // Prints D with a tab and backslash.
        System.out.println("\tD\\");

        // Prints E inside quotation marks.
        System.out.println("\"E\"");

        // F is a comment, so it does not print.
        // System.out.println("F");

        // Prints G.
        System.out.print("G");
        System.out.println();

        // Prints my name.
        System.out.println("Sydney Chance");

        // Prints my major.
        System.out.println("Computer Science");

        // Prints my class year.
        System.out.println("Class of 2029");

        // Prints my information with one print statement.
        System.out.print("Sydney Chance\nComputer Science\nClass of 2029\n");

        // Prints the table headings.
        System.out.println("Day\t\tClass\t\tTime");

        // Prints Monday's class.
        System.out.println("Mon\t\tCSCI-121\t2:00 PM");

        // Prints Tuesday's class.
        System.out.println("Tue\t\tCSCI-121\t3:00 PM");

        // Prints a quote.
        System.out.println("My teacher said \"type it yourself.\"");

        // Prints a file path.
        System.out.println("My code lives in C:\\Users\\jordan\\csci121");
    }
}

