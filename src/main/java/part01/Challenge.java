public class Challenge {
    public static void main(String[] args) {
        // Prints the top of the robot.
        System.out.println("\t+------+");

        // Prints the robot's eyes.
        System.out.println("\t| O  O |");

        // Prints the robot's mouth.
        System.out.println("\t|  --  |");

        // Prints the robot's body.
        System.out.println("\t| /\\/ |");

        // Prints the bottom of the robot.
        System.out.println("\t+------+");

        // Prints a quote and a backslash.
        System.out.print("\"Beep\" \\o/\n");
    }
}

