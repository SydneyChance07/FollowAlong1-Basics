public class Stretch {
    public static void main(String[] args) {
        // Stores two numbers.
        int a = 7;
        double b = 7;

        // Prints the values.
        System.out.println(a);
        System.out.println(b);

        // Prints the text exactly as written.
        System.out.println("a + b");

        // Prints the label and value.
        System.out.println("a: " + a);

        // Joins the two numbers as text.
        System.out.println("" + a + a);

        // Adds the numbers first.
        System.out.println(a + a + "!");

        // Stores one character.
        char c = 'A';
        System.out.println(c);

        // Stores a true or false value.
        boolean on = true;
        System.out.println(on);

        // Stores my information.
        String name = "Sydney Chance";
        int age = 19;
        double gpa = 3.06;
        boolean commuter = true;

        // Prints my information.
        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("GPA: " + gpa);
        System.out.println("Commuter: " + commuter);

        // Stores more example variables.
        char initial = 'S';
        int classes = 4;
        double credits = 12.0;
        boolean works = false;
        String subject = "Computer Science";

        // Prints the example information.
        System.out.println(initial + " takes " + classes + " classes in "
                + subject + ", for " + credits
                + " credit hours. Has a job: " + works);

        // Stores a city.
        String city = "Dover";

        // Stores a large number.
        long people = 4000000000L;

        // Stores a letter.
        char grade = 'B';

        // Stores a decimal.
        float temp = 72.5f;

        // Prints the values.
        System.out.println(city);
        System.out.println(people);
        System.out.println(grade);
        System.out.println(temp);
    }
}


